const MISSING = '[будет указано]';

/** Company details come from LEGAL_* variables; anything unset is shown as "[будет указано]" and reported by legalDetailsMissing(). */
export function legalValuesFromEnv(env: NodeJS.ProcessEnv, settings: { accountRetentionDays: number; leadRetentionDays: number }): LegalValues {
  const pick = (key: string) => env[key]?.trim() || MISSING;
  let appHost = MISSING;
  try { if (env.PUBLIC_APP_URL) appHost = new URL(env.PUBLIC_APP_URL).host; } catch { /* keep placeholder */ }
  const bot = env.TELEGRAM_BOT_USERNAME?.trim();
  return {
    operatorName: pick('LEGAL_OPERATOR_NAME'),
    operatorBin: pick('LEGAL_OPERATOR_BIN'),
    operatorAddress: pick('LEGAL_OPERATOR_ADDRESS'),
    operatorBank: pick('LEGAL_OPERATOR_BANK'),
    supportEmail: pick('LEGAL_SUPPORT_EMAIL'),
    privacyEmail: env.LEGAL_PRIVACY_EMAIL?.trim() || pick('LEGAL_SUPPORT_EMAIL'),
    appHost,
    sitesDomain: env.SITES_BASE_DOMAIN?.trim() || MISSING,
    botName: bot ? `@${bot.replace(/^@/, '')}` : MISSING,
    hostingProvider: pick('LEGAL_HOSTING_PROVIDER'),
    backupStorage: env.LEGAL_BACKUP_STORAGE?.trim() || 'на том же сервере',
    accountRetentionDays: settings.accountRetentionDays,
    leadRetentionDays: settings.leadRetentionDays,
  };
}

export function legalDetailsMissing(env: NodeJS.ProcessEnv): string[] {
  return ['LEGAL_OPERATOR_NAME', 'LEGAL_OPERATOR_BIN', 'LEGAL_OPERATOR_ADDRESS', 'LEGAL_SUPPORT_EMAIL', 'LEGAL_HOSTING_PROVIDER']
    .filter((key) => !env[key]?.trim());
}

export function renderLegal(key: LegalDocumentKey, values: LegalValues): string {
  const text = key === 'terms' ? TERMS : PRIVACY;
  return text
    .replaceAll('{{version}}', LEGAL_VERSIONS[key])
    .replaceAll('{{date}}', formatDate(LEGAL_EFFECTIVE_DATE[key]))
    .replace(/\{\{(\w+)\}\}/g, (_, name: string) => String((values as unknown as Record<string, string | number>)[name] ?? MISSING));
}

function formatDate(iso: string): string {
  return new Date(`${iso}T00:00:00Z`).toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' });
}

