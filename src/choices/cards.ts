export function recommend(card: CardKey, project: { hasSpecialists: boolean; projectType?: string | null }): { optionKey: string; reason: string } {
  if (card === 'code_hosting' && project.projectType === 'web_app') {
    return { optionKey: 'github', reason: 'Код приложения нужно где-то хранить, чтобы его запустить: Render берёт его из GitHub, а агент отправляет туда каждую версию отдельной веткой. GitHub бесплатен и для закрытых репозиториев.' };
  }
  if (card === 'technologies') {
    return { optionKey: 'buildpath', reason: 'BuildPath сам соберёт и проверит такой сайт, а файлы останутся вашими. Свой стек нужен, только если требуется то, чего здесь нет: оплата онлайн, личный кабинет, интеграции.' };
  }
  if (card === 'domain') {
    return { optionKey: 'buildpath_address', reason: 'Начните с бесплатного адреса BuildPath: сайт заработает сразу. Свой домен можно подключить позже, ничего не переделывая.' };
  }
  if (card === 'deployment') {
    return { optionKey: 'buildpath', reason: 'Это самый простой вариант: публикация одной кнопкой, работают форма заявок и онлайн-запись, а обслуживание сервера — наша забота.' };
  }
  return project.hasSpecialists
      ? { optionKey: 'github', reason: 'В проекте работают специалисты: им удобнее брать код из GitHub, и у вас будет история всех версий.' }
      : { optionKey: 'archive', reason: 'Сайт уже работает на BuildPath, а копия нужна на случай переезда. Архива достаточно, пока вы не подключаете разработчика.' };
}

